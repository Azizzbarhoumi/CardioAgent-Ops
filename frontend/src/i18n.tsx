export type Lang = 'en' | 'fr';
export const dictionaries: Record<Lang, Record<Key, string>> = { en, fr };
export const LANG_STORAGE_KEY = 'heart-lab-lang';

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

type Ctx = { lang: Lang; setLang(l: Lang): void; t(key: Key, vars?: Record<string, string | number>): string };
const I18nContext = createContext<Ctx>({ lang: 'en', setLang: () => undefined, t: (k, v) => translate('en', k, v) });

function readStoredLang(): Lang {
  try { return localStorage.getItem(LANG_STORAGE_KEY) === 'fr' ? 'fr' : 'en'; } catch { return 'en'; }
}

export function I18nProvider({ children, initial }: { children: ReactNode; initial?: Lang }) {
  const [lang, setLangState] = useState<Lang>(() => initial ?? readStoredLang());
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(LANG_STORAGE_KEY, l); } catch { /* storage may be blocked */ }
  }, []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const value = useMemo<Ctx>(() => ({ lang, setLang, t: (k, v) => translate(lang, k, v) }), [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);

/** Model names come from the API in English; they are shown through the dictionary when the key is known. */
export function modelName(t: Ctx['t'], key: string, apiName: string, short = false): string {
  const k = `model.${short ? 'short.' : ''}${key}` as Key;
  return k in en ? t(k) : apiName;
}
/** The API label ("Normal"/"Abnormal") is displayed as returned in English and translated in French. */
export function labelText(t: Ctx['t'], prediction: 0 | 1, apiLabel: string, lang: Lang): string {
  return lang === 'en' ? apiLabel : t(prediction === 1 ? 'label.abnormal' : 'label.normal');
}
